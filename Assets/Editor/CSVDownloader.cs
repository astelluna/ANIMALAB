using NUnit.Framework;
using System.Collections.Generic;
using System.Linq;
using System.Net;
using UnityEditor;
using UnityEngine;

public class CSVDownloader : MonoBehaviour
{
    const string nodeUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=0#gid=0";
    const string choiceUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=905363447";
    const string choiceConditionUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=831253886";
    const string rewardUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=681914727";
    const string cgUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=453507803";
    const string characterSpriteUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=503407958";
    const string dialogSoundUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=570984018";
    const string chapterDataUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=452500722";
    const string ItemDataUrl = "https://docs.google.com/spreadsheets/d/1qE7r5AmRDthtMOsAru4YtmnxGdrOfOpFH-iEM1lKf0Y/export?format=csv&gid=984075129";
    [MenuItem("Tools/Download CSV File & Make JSON")]
    public static void DownloadCSVAndMakeJSON()
    {
        WebClient client = new WebClient();

        client.DownloadFile(nodeUrl, PathManager.nodeFileName);
        client.DownloadFile(choiceUrl, PathManager.choiceFileName);
        client.DownloadFile(choiceConditionUrl,  PathManager.choiceConditionFileName);
        client.DownloadFile(rewardUrl, PathManager.rewardFileName);
        client.DownloadFile(cgUrl, PathManager.cgFileName);
        client.DownloadFile(characterSpriteUrl, PathManager.characterSpriteFileName);
        client.DownloadFile(dialogSoundUrl, PathManager.dialogSoundFileName);
        client.DownloadFile(chapterDataUrl, PathManager.chapterDataFileName);
        client.DownloadFile(ItemDataUrl, PathManager.itemDataFileName);
        AssetDatabase.Refresh();
        Debug.Log("CSV 다운로드 완료. " + PathManager.csvPath);

        //이후 JSON으로 변환도 자동으로 해버리자
        CSVToJsonWindow.ReadCSV();
        AssetDatabase.Refresh();
        Debug.Log("CSV -> JSON 변환 완료. " + PathManager.storyJsonFilePath);
        //SO들이 빈 키값을 자동으로 채우도록 자동화
        AutoRegisterRewardSO();
        AutoGeneratedBackgroundSO();
        AutoGeneratedThumbnailSO();
        AutoGeneratedItemSO();
        AutoGeneratedEndingSO();
    }
    private static void AutoRegisterRewardSO()
    {
        DialogData[] jsonData = JsonDataManager.GetJsonData();

        List<(string, eDialogItemType)> allKeyUsed = new List<(string, eDialogItemType)>();
        foreach (DialogData item in jsonData)
        {
            foreach (DialogReward rewardData in item.reward)
            {
                string key = rewardData.key;
                if (!allKeyUsed.Any(x => x.Item1 == rewardData.key))
                {
                    allKeyUsed.Add((rewardData.key, rewardData.Type));
                }
            }
        }
        RewardIconSO table = AssetDatabase.LoadAssetAtPath<RewardIconSO>("Assets/RewardIconSO.asset");
        if(table == null)
        {
            Debug.LogError("RewardIconSO가 null입니다. 경로를 확인해주세요");
        }
        foreach ((string, eDialogItemType) tuple in allKeyUsed)
        {
            RewardIconEntry data = table.rewardDataList.Find(e => e.key == tuple.Item1);
            if (data == null)
            {
                table.rewardDataList.Add(new RewardIconEntry()
                {
                    key = tuple.Item1,
                    type = tuple.Item2,
                });
                Debug.Log($"누락되 키와 타입 추가= {tuple.Item1}, {tuple.Item2}");
            }
            else
            {
                data.key = tuple.Item1;
                data.type = tuple.Item2;
            }
        }
        EditorUtility.SetDirty(table);
        AssetDatabase.SaveAssets();
        Debug.Log("RewardIconSo 동기화 완료");
    }
    private static void AutoGeneratedBackgroundSO()
    {
        DialogData[] jsonData = JsonDataManager.GetJsonData();

        Dictionary<string, DialogCG> allKeyUsed = new Dictionary<string, DialogCG>();
        foreach (DialogData item in jsonData)
        {
            foreach (DialogCG cgData in item.cg)
            {
                string key = cgData.key;
                if(!allKeyUsed.ContainsKey(key))
                {
                    allKeyUsed.Add(key, cgData);
                }
            }
        }
        CGDatabaseSO table = AssetDatabase.LoadAssetAtPath<CGDatabaseSO>("Assets/Resources/CG/SO/CGDatabaseSO.asset");
        if (table == null)
        {
            Debug.LogError("BackgroundDatabaseSO가 null입니다. 경로를 확인해주세요");
            return;
        }
        foreach (DialogCG dialogCG in allKeyUsed.Values)
        {
            CGData data = table.backgroundDatas.Find(e => e.key == dialogCG.key);
            Debug.Log($"[체크] key={dialogCG.key}, Category={dialogCG.Category}");
            if (data== null)
            {
                table.backgroundDatas.Add(new CGData()
                {
                    key = dialogCG.key,
                    category = dialogCG.Category
                });
                Debug.Log($"cg -누락된 키 추가= {dialogCG}");
            }
            else
            {
                //이미 있으면 CSV와 동일하게 맞춰준다
                data.key = dialogCG.key;
                data.category = dialogCG.Category;
            }
        }
        EditorUtility.SetDirty(table);
        AssetDatabase.SaveAssets();
        Debug.Log("BackgroundSo 동기화 완료");
    }
    private static void AutoGeneratedThumbnailSO()
    {
        List<ChapterData> chapterDataList = JsonDataManager.GetChapterDataClass();

        HashSet<string> allKeyUsed = new HashSet<string>();
        foreach (ChapterData data in chapterDataList)
        {
            string key = data.thumbnailKey;
            if (!allKeyUsed.Contains(key))
            {
                allKeyUsed.Add(key);
            }
        }
        ChapterThumbnailDatabaseSO table = AssetDatabase.LoadAssetAtPath<ChapterThumbnailDatabaseSO>("Assets/Resources/ChapterThumbnail/SO/ChapterThumbnailDatabaseSO.asset");
        if (table == null)
        {
            Debug.LogError("ChapterThumbnailDatabaseSO가 null입니다. 경로를 확인해주세요");
            return;
        }
        foreach (string id in allKeyUsed)
        {
            ChapterThumbnail data = table.chapterThumbnails.Find(e => e.key == id);
            if (data == null)
            {
                table.chapterThumbnails.Add(new ChapterThumbnail()
                {
                    key = id
                });
                Debug.Log($"chapterThumbnail -누락된 키 추가= {id}");
            }
            else
            {
                data.key = id;
            }
        }
        EditorUtility.SetDirty(table);
        AssetDatabase.SaveAssets();
        Debug.Log("ChapterThumbnail 동기화 완료");
    }
    private static void AutoGeneratedItemSO()
    {
        List<ItemClassJson> itemDataList = JsonDataManager.GetItemDataToJson().itemClassList;
        Dictionary<string, ItemClassJson> allKeyUsed = new Dictionary<string, ItemClassJson>();

        foreach (ItemClassJson data in itemDataList)
        {
            string key = data.key;
            if (!allKeyUsed.ContainsKey(key))
            {
                allKeyUsed.Add(key,data);
            }
        }
        ItemDataSO table = AssetDatabase.LoadAssetAtPath<ItemDataSO>("Assets/Resources/Item/SO/ItemData.asset");
        if (table == null)
        {
            Debug.LogError("ItemDataSO가 null입니다. 경로를 확인해주세요");
            return;
        }
        foreach (ItemClassJson item in allKeyUsed.Values)
        {
            ItemDataClass data = table.ItemDataClassList.Find(e => e.ItemId == item.key);
            if (data == null)
            {
                ItemDataClass itemDataClass = new ItemDataClass();
                itemDataClass.SetItemData(item.key, item.explain);
                table.ItemDataClassList.Add(itemDataClass);
                Debug.Log($"ItemDataSO -누락된 키 추가= {item.key}");
            }
            else
            {
                data.SetItemData(item.key, item.explain);
            }
        }
        EditorUtility.SetDirty(table);
        AssetDatabase.SaveAssets();
        Debug.Log("ItemDataSO 동기화 완료");
    }
    private static void AutoGeneratedEndingSO()
    {
        DialogData[] jsonData = JsonDataManager.GetJsonData();

        //List<(string, eDialogItemType)> allKeyUsed = new List<(string, eDialogItemType)>();
        HashSet<string> hash = new HashSet<string>();

        foreach (DialogData item in jsonData)
        {
            if (item.EndingKey == "") continue;
            if (hash.Contains(item.EndingKey))
            {
                Debug.LogError($"{item.EndingKey} 엔딩이름이 중복이어서 넘어갔습니다 csv 확인해주세요");
                continue;
            }
            hash.Add(item.EndingKey);
        }
        EndingDatabaseSO table = AssetDatabase.LoadAssetAtPath<EndingDatabaseSO>("Assets/Resources/Ending/EndingDatabaseSO.asset");
        if (table == null)
        {
            Debug.LogError("EndingDatabaseSO가 null입니다. 경로를 확인해주세요");
        }
        foreach( string endingKey in hash)
        {
            EndingData data = table.endingDataList.Find(e => e.key == endingKey);
            if(data == null)
            {
                table.endingDataList.Add(new EndingData()
                {
                    key = endingKey
                });
            }
            else
            {
                data.key = endingKey; //할거없음.
            }
        }
        EditorUtility.SetDirty(table);
        AssetDatabase.SaveAssets();
        Debug.Log("EndingDatabaseSO 동기화 완료");
    }
}
